"""AI Market Interpreter + Decision Pipeline for the ATS Pro Terminal.

Turns the engine's OWN engineered features (trading_assistant.agents.
features.build_features) for the latest CLOSED candle into a structured,
plain-language read of the market, and reconstructs where the current
recommendation stands in the decision pipeline.

Design rules held here, matching the platform's principles:
- Data-driven, never fabricated: every number is a real computed feature
  or a real journal record. The natural-language explanation is TEMPLATED
  from those numbers (deterministic string formatting), not generated by
  an LLM - so it can never hallucinate, and it costs no tokens.
- No look-ahead: reads only the last closed candle's features; nothing
  here peeks at future bars (this is descriptive, not predictive).
- No hardcoded verdicts: thresholds are the same standard-TA constants the
  engine's classify_regime/classify_market_condition already use, and the
  buy/sell thresholds come from config, not literals.
- Read-only: this module never writes any database and never places an
  order - the Pro Terminal is the brain, not the operator.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

import numpy as np
import pandas as pd

from trading_assistant.agents.features import (
    build_features,
    classify_market_condition,
    classify_regime,
)
from trading_assistant.config import Config
from trading_assistant.persistence.journal import Journal
from webapp import data_access as da


def _latest_feature_row(config: Config, symbol: str, timeframe: str) -> Optional[pd.Series]:
    raw = da.fetch_ohlcv(config, symbol, timeframe, limit=300)
    frame = pd.DataFrame(raw)
    if frame.empty or len(frame) < 40:
        return None
    frame["timestamp"] = pd.to_datetime(frame["timestamp"], unit="ms", utc=True)
    frame = frame.iloc[:-1]  # closed candles only - the last row is still forming
    featured = build_features(frame)
    if featured.empty:
        return None
    row = featured.iloc[-1]
    # A row whose slowest-indicator inputs never warmed up is not a usable
    # read - report "no data" rather than a half-NaN interpretation.
    if pd.isna(row.get("adx_strength")) or pd.isna(row.get("rsi_normalized")):
        return None
    return row


def _clip(x: float, lo: float = -1.0, hi: float = 1.0) -> float:
    return float(np.clip(x, lo, hi))


def _f(row: pd.Series, key: str, default: float = 0.0) -> float:
    v = row.get(key, default)
    return default if v is None or pd.isna(v) else float(v)


def interpret_market(config: Config, symbol: str, timeframe: str) -> Dict[str, Any]:
    """The Market Interpreter payload - or {available: False} when there is
    not enough history to read honestly."""
    row = _latest_feature_row(config, symbol, timeframe)
    if row is None:
        return {"symbol": symbol, "timeframe": timeframe, "available": False}

    sma_fast_vs_slow = _f(row, "sma_fast_vs_slow")
    adx_strength = _f(row, "adx_strength")
    adx_directional = _f(row, "adx_directional")
    rsi = _f(row, "rsi_normalized")  # 0..1
    macd_hist_pct = _f(row, "macd_hist_pct")
    roc_pct = _f(row, "roc_pct")
    atr_pct = _f(row, "atr_pct")
    bb_width = _f(row, "bb_width_pct")
    rel_volume = _f(row, "relative_volume", 1.0)
    obv_z = _f(row, "obv_zscore")
    body_ratio = _f(row, "candle_body_ratio")
    smc_state = _f(row, "smc_structure_state")
    smc_bos = _f(row, "smc_bos")
    smc_mss = _f(row, "smc_mss")

    regime = classify_regime(sma_fast_vs_slow, adx_strength)
    condition = classify_market_condition(atr_pct, rel_volume)

    # --- Directional sub-signals, each bounded to [-1, 1] ---
    trend_dir = _clip(adx_directional * 3 + np.sign(sma_fast_vs_slow) * adx_strength)
    momentum = _clip((rsi - 0.5) * 2 * 0.5 + np.tanh(macd_hist_pct * 50) * 0.3 + np.tanh(roc_pct * 5) * 0.2)
    # Buyer-vs-seller pressure: candle bodies + OBV drift + directional
    # trend strength + which side the volume is leaning, all real features.
    pressure = _clip(body_ratio * 0.4 + np.tanh(obv_z) * 0.3 + adx_directional * 2 * 0.3)
    structure = _clip(smc_state + smc_bos * 0.3 - 0.0 + smc_mss * 0.2)

    # --- Non-directional magnitudes, [0, 1] ---
    # Scaled against ordinary crypto ranges (ATR ~0-8% -> panic threshold,
    # BB width similar) so the bar is readable, not a raw fraction.
    volatility = _clip(atr_pct / 0.08 * 0.6 + min(bb_width, 0.2) / 0.2 * 0.4, 0.0, 1.0)
    liquidity = _clip(rel_volume / 2.0, 0.0, 1.0)  # 1.0 == 2x the 20-bar average

    # Interpreter confidence = agreement among the directional reads. Four
    # signals all pointing the same way -> a clear picture; a tug-of-war ->
    # low. This is a READING-CLARITY score, explicitly NOT the model's
    # prediction confidence (which lives on the AI Prediction card).
    dirs = [trend_dir, momentum, pressure, structure]
    mean_dir = float(np.mean(dirs))
    agreement = 1.0 - float(np.mean([abs(d - mean_dir) for d in dirs]))
    reading_clarity = _clip(abs(mean_dir) * 0.5 + agreement * 0.5, 0.0, 1.0)

    dna = {
        "trend": round(trend_dir, 3),
        "momentum": round(momentum, 3),
        "pressure": round(pressure, 3),
        "structure": round(structure, 3),
        "volatility": round(volatility, 3),
        "liquidity": round(liquidity, 3),
    }

    return {
        "symbol": symbol,
        "timeframe": timeframe,
        "available": True,
        "regime": regime,
        "condition": condition,  # 'panic' | 'illiquid' | None
        "reading_clarity": round(reading_clarity, 3),
        "metrics": {
            "trend": {"value": round(trend_dir, 3), "label": _band(trend_dir, "up", "down", "flat")},
            "momentum": {"value": round(momentum, 3), "label": _band(momentum, "rising", "falling", "neutral"), "rsi": round(rsi * 100, 1)},
            "structure": {"value": round(structure, 3), "label": _band(structure, "bullish", "bearish", "ranging"),
                          "bos": bool(smc_bos), "mss": bool(smc_mss)},
            "pressure": {"value": round(pressure, 3), "label": _band(pressure, "buyers", "sellers", "balanced")},
            "volatility": {"value": round(volatility, 3), "label": _magnitude(volatility), "atr_pct": round(atr_pct * 100, 2)},
            "liquidity": {"value": round(liquidity, 3), "label": _magnitude(liquidity), "rel_volume": round(rel_volume, 2)},
        },
        "dna": dna,
        "explanation": _explain(symbol, regime, condition, trend_dir, momentum, pressure,
                                structure, volatility, liquidity, rsi, reading_clarity),
    }


def _band(v: float, pos: str, neg: str, mid: str, dead: float = 0.15) -> str:
    if v > dead:
        return pos
    if v < -dead:
        return neg
    return mid


def _magnitude(v: float) -> str:
    if v >= 0.66:
        return "high"
    if v >= 0.33:
        return "moderate"
    return "low"


def _explain(symbol, regime, condition, trend, momentum, pressure, structure,
             volatility, liquidity, rsi, clarity) -> str:
    """Deterministic natural-language read, composed from the real metrics
    above. No model, no LLM - the same inputs always produce the same
    sentence."""
    regime_phrase = {
        "trending_up": "in an uptrend",
        "trending_down": "in a downtrend",
        "ranging": "ranging (no dominant trend)",
    }.get(regime, regime)

    parts: List[str] = [f"{symbol} is {regime_phrase}"]

    mom = _band(momentum, "rising", "fading", "flat")
    parts.append(f"momentum is {mom} (RSI {rsi * 100:.0f})")

    if pressure > 0.15:
        parts.append("buyers are in control")
    elif pressure < -0.15:
        parts.append("sellers are in control")
    else:
        parts.append("buyer/seller pressure is balanced")

    vol_word = _magnitude(volatility)
    liq_word = _magnitude(liquidity)
    parts.append(f"volatility is {vol_word} and liquidity is {liq_word}")

    text = ", ".join(parts) + "."

    if condition == "panic":
        text += " Conditions are dislocated (extreme volatility) — the engine sits out regardless of direction."
    elif condition == "illiquid":
        text += " Volume is unusually thin — the engine sits out until liquidity returns."

    if clarity < 0.3:
        text += " Signals conflict, so this read is low-confidence."
    return text


# ---------------------------------------------------------------------------
# Decision Pipeline
# ---------------------------------------------------------------------------

_STAGES = ["market_data", "market_interpreter", "feature_extraction", "model_voting", "risk_check"]


def decision_pipeline(config: Config, db_path: str, symbol: str) -> Dict[str, Any]:
    """Where the current recommendation stands, stage by stage, plus the
    plain reason for a HOLD. Reads the interpreter (above) and the engine's
    own journal (pure reader) - never writes, never trades."""
    interp = interpret_market(config, symbol, config.timeframe)

    journal = Journal(db_path, initialize=False)
    try:
        decisions = list(journal.recent_decisions(symbol=symbol, limit=1, exclude_paper=True))
    except Exception:  # noqa: BLE001 - schema-behind reader (see Journal.__init__) => no decisions yet
        decisions = []
    try:
        breaker = journal.latest_circuit_breaker_event()
    except Exception:  # noqa: BLE001
        breaker = None
    try:
        snapshot = journal.latest_equity_snapshot()
    except Exception:  # noqa: BLE001
        snapshot = None

    decision = decisions[0] if decisions else None
    details = (decision or {}).get("details", {}) or {}
    signal = decision["signal"] if decision else None
    champion = details.get("champion")
    prob_up = details.get("probability_up")
    regime = details.get("regime") or interp.get("regime")
    risk_approved = decision.get("risk_approved") if decision else None
    risk_reason = decision.get("risk_reason") if decision else None
    breaker_tripped = bool(breaker["tripped"]) if breaker else False

    buy_t = config.prediction.buy_threshold
    sell_t = config.prediction.sell_threshold

    position = None
    if snapshot:
        position = (snapshot.get("positions") or {}).get(symbol)
    has_position = bool(position and position.get("quantity"))

    # --- Stage states: "ok" | "pending" | "blocked" ---
    stages: List[Dict[str, str]] = []

    def add(name: str, state: str, detail: str) -> None:
        stages.append({"stage": name, "state": state, "detail": detail})

    add("market_data", "ok" if interp["available"] else "pending",
        "live candles" if interp["available"] else "insufficient history")
    add("market_interpreter", "ok" if interp["available"] else "pending",
        f"regime: {interp.get('regime', '—')}" if interp["available"] else "—")
    add("feature_extraction", "ok" if interp["available"] else "pending",
        "features computed" if interp["available"] else "—")

    if interp.get("condition") in ("panic", "illiquid"):
        add("model_voting", "blocked", f"sitting out ({interp['condition']})")
    elif champion:
        add("model_voting", "ok", f"champion: {champion}")
    else:
        add("model_voting", "pending", f"no champion for {regime or 'current regime'}")

    if breaker_tripped:
        add("risk_check", "blocked", "circuit breaker tripped")
    elif risk_approved is False:
        add("risk_check", "blocked", risk_reason or "risk engine blocked")
    elif decision is not None:
        add("risk_check", "ok", "approved")
    else:
        add("risk_check", "pending", "no decision yet")

    # --- Terminal decision + honest HOLD reason ---
    hold_reason = None
    if signal in ("BUY", "SELL"):
        decision_label = signal
    else:
        decision_label = "HOLD"
        if breaker_tripped:
            hold_reason = "circuit breaker tripped — trading halted"
        elif interp.get("condition") in ("panic", "illiquid"):
            hold_reason = f"sitting out — {interp['condition']} conditions"
        elif champion is None and decision is not None:
            hold_reason = f"no promoted model for the current regime ({regime or '—'})"
        elif risk_approved is False:
            hold_reason = f"risk engine blocked: {risk_reason or 'unspecified'}"
        elif prob_up is not None and sell_t < prob_up < buy_t:
            hold_reason = (f"confidence too low (prob up {prob_up * 100:.0f}%, "
                           f"needs ≥{buy_t * 100:.0f}% to buy or ≤{sell_t * 100:.0f}% to sell)")
        elif decision is None:
            hold_reason = "no real decision recorded for this symbol yet"
        else:
            hold_reason = "holding"

    execution = "position open" if has_position else "waiting"

    return {
        "symbol": symbol,
        "stages": stages,
        "decision": decision_label,
        "hold_reason": hold_reason,
        "execution": execution,
        "decision_at": decision["timestamp"] if decision else None,
    }
